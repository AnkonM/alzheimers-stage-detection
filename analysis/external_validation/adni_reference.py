"""ADNI train-only reference numbers for the OASIS external-validation protocol.

Reads ONLY ADNI train-split subjects (cross-fitted / out-of-fold predictions that
already exist in the repo) and writes aggregate statistics. It never opens any
frozen test-split output, never reads test-split rows, and writes no subject-level
values.

Run from the repo root with LYP/.venv-app:
    python -m analysis.external_validation.adni_reference
"""
import json
import pathlib

import numpy as np
import pandas as pd
from scipy.stats import rankdata

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).with_name("adni_reference.json")
PROTOCOL = ROOT / "docs" / "external_validation_protocol.md"
BEGIN, END = "<!-- ADNI_REFERENCE:BEGIN (generated by analysis/external_validation/adni_reference.py) -->", "<!-- ADNI_REFERENCE:END -->"
SEED = 20261113
N_BOOT = 2000
CODES = {0: "CN", 1: "EMCI", 2: "LMCI", 3: "AD"}


def auc(pos, neg):
    """Mann-Whitney AUC, ties get half credit."""
    x = np.concatenate([pos, neg])
    r = rankdata(x)
    n1, n0 = len(pos), len(neg)
    return float((r[:n1].sum() - n1 * (n1 + 1) / 2) / (n1 * n0))


def boot_ci(pos, neg, rng):
    a = np.empty(N_BOOT)
    for b in range(N_BOOT):
        a[b] = auc(rng.choice(pos, len(pos)), rng.choice(neg, len(neg)))
    return [float(np.percentile(a, 2.5)), float(np.percentile(a, 97.5))]


def two_contrasts(score, y, rng):
    out = {}
    cn, ad, rest = score[y == 0], score[y == 3], score[y != 3]
    out["CN_vs_AD"] = {"auc": auc(ad, cn), "ci95": boot_ci(ad, cn, rng), "n_pos": int(len(ad)), "n_neg": int(len(cn))}
    out["AD_vs_rest"] = {"auc": auc(ad, rest), "ci95": boot_ci(ad, rest, rng), "n_pos": int(len(ad)), "n_neg": int(len(rest))}
    return out


def by_group(score, y):
    return {CODES[k]: {"n": int((y == k).sum()), "mean": float(score[y == k].mean()), "sd": float(score[y == k].std(ddof=1))}
            for k in range(4) if (y == k).sum() > 1}


def f3(x):
    return f"{x:.3f}"


def render_md(res):
    """Markdown block for the protocol; every number comes from `res`."""
    L = [BEGIN, "",
         f"ADNI train-split reference values (n = ALZ {res['ALZ']['n']}, BAG {res['BAG']['n']}, specialist "
         f"{res['MRI_specialist_Pad']['n']}; out-of-fold or cross-fitted predictions; the frozen test split is not read). "
         f"AUC with {res['n_boot']}-resample subject-level percentile bootstrap 95% CI, seed {res['seed']}.", "",
         "| Quantity | CN vs AD AUC [95% CI] | AD vs rest AUC [95% CI] |", "|---|---|---|"]
    for key, name in (("ALZ", "ALZ (cross-fitted)"), ("BAG", "Brain-age gap (corrected)"),
                      ("MRI_specialist_Pad", "MRI specialist P(AD) (OOF, mean of 5 seeds)")):
        d = res[key]
        c, r = d["CN_vs_AD"], d["AD_vs_rest"]
        L.append(f"| {name} | {f3(c['auc'])} [{f3(c['ci95'][0])}, {f3(c['ci95'][1])}] (n {c['n_pos']} / {c['n_neg']}) "
                 f"| {f3(r['auc'])} [{f3(r['ci95'][0])}, {f3(r['ci95'][1])}] (n {r['n_pos']} / {r['n_neg']}) |")
    L += ["", "| Group | ALZ mean (SD) | BAG mean (SD), years | Specialist P(AD) mean (SD) |", "|---|---|---|---|"]
    for g in ("CN", "EMCI", "LMCI", "AD"):
        a, b, m = (res[k]["by_group"][g] for k in ("ALZ", "BAG", "MRI_specialist_Pad"))
        L.append(f"| {g} (n {a['n']}) | {f3(a['mean'])} ({f3(a['sd'])}) | {b['mean']:+.2f} ({b['sd']:.2f}) "
                 f"| {f3(m['mean'])} ({f3(m['sd'])}) |")
    bag = res["BAG"]
    L += ["", f"BAG bias fit (CN train, n {bag['n_cn_fit']}): predicted age = {bag['alpha']:.3f} x age + {bag['beta']:.2f}; "
          f"ADNI train age at scan {bag['age_range_train_scan'][0]:.1f} to {bag['age_range_train_scan'][1]:.1f} years.",
          "", END]
    return "\n".join(L)


def update_protocol(md):
    text = PROTOCOL.read_text()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    new = text[:a] + md + text[b:]
    if new != text:
        PROTOCOL.write_text(new)
    return new != text


def main():
    rng = np.random.default_rng(SEED)
    res = {"seed": SEED, "n_boot": N_BOOT, "split": "train only (subjects with clin_split == 'train')",
           "test_split_read": False}

    # ---- ALZ: cross-fitted over folds (alz_crossfit.csv) ----
    cf = pd.read_csv(ROOT / "analysis/fusion_feasibility/alz_crossfit.csv")
    assert set(cf.clin_split.unique()) <= {"train", "val"}
    tr = cf[(cf.clin_split == "train") & cf.has_mri.astype(bool)].dropna(subset=["ALZ"])
    y = tr.label.to_numpy().astype(int)
    assert set(np.unique(y)) <= {0, 1, 2, 3}
    res["ALZ"] = {"n": int(len(tr)), "by_group": by_group(tr.ALZ.to_numpy(), y), **two_contrasts(tr.ALZ.to_numpy(), y, rng)}
    train_rids = set(cf[cf.clin_split == "train"].RID.astype(int))

    # ---- BAG: bias fit on CN train only (p2_ablation.py convention) ----
    bg = pd.read_csv(ROOT / "analysis/brain_age/brainage_trainval.csv")
    bg = bg[(bg.split == "train") & bg.has_brainage.astype(bool)].copy()
    cn = bg[bg.DX_bl == "CN"]
    alpha, beta = np.polyfit(cn.age_at_scan, cn.pred_age, 1)
    bg["bag"] = (bg.pred_age - beta) / alpha - bg.age_at_scan
    yb = bg.label.to_numpy().astype(int)
    res["BAG"] = {"n": int(len(bg)), "alpha": float(alpha), "beta": float(beta), "n_cn_fit": int(len(cn)),
                  "age_range_train_scan": [float(bg.age_at_scan.min()), float(bg.age_at_scan.max())],
                  "by_group": by_group(bg.bag.to_numpy(), yb), **two_contrasts(bg.bag.to_numpy(), yb, rng)}

    # ---- MRI specialist: single-level OOF streams over train+val; keep train rows only ----
    z = np.load(ROOT / "analysis/fusion_v3/frozen/streams_final.npz")
    rids, ys, has = z["rids"].astype(int), z["y"].astype(int), z["has"].astype(bool)
    keep = np.array([r in train_rids for r in rids]) & has
    pad = np.mean([z[f"mri_oof_{s}"][:, 3] for s in (42, 43, 44, 45, 46)], axis=0)
    res["MRI_specialist_Pad"] = {"n": int(keep.sum()), "note": "mean over 5 seeds of OOF P(AD); positive = AD",
                                 "by_group": by_group(pad[keep], ys[keep]), **two_contrasts(pad[keep], ys[keep], rng)}

    # age + sex benchmark is computed in the protocol analysis, not here (needs OASIS columns)
    OUT.write_text(json.dumps(res, indent=2, sort_keys=True) + "\n")
    print("wrote", OUT.relative_to(ROOT))
    if PROTOCOL.exists() and BEGIN in PROTOCOL.read_text():
        print("protocol block", "updated" if update_protocol(render_md(res)) else "unchanged")


if __name__ == "__main__":
    main()

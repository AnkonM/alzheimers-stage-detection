#!/usr/bin/env python3
"""Write docs/model_card.md, the single source for the Model Card page. Every number is read from a committed
results file (docs/validation/oasis_analysis.json and oasis_domain_shift.json for the external validation section, analysis/fusion_v3/frozen_run/test_results.json, tests/parity/*.md, analysis/volume_agreement/results,
analysis/inference_refs/results, analysis/explainability/results); the prose below carries no metric.

    python tools/build_model_card.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.assessment.schema import ALZ_BATCH_CAVEAT, MODE_LABELS  # noqa: E402

sys.path.insert(0, str(ROOT / "tools"))
import oasis_render  # noqa: E402

J = lambda p: json.loads((ROOT / p).read_text())  # noqa: E731
T = J("analysis/fusion_v3/frozen_run/test_results.json")
REF = J("analysis/inference_refs/results/reference_ranges.json")
AGR = J("analysis/volume_agreement/results/agreement.json")
REG = J("src/assessment/artifacts/registry.json")
EV = J("analysis/explainability/results/eval_status.json")
RULES = J("analysis/inference_refs/results/rules.json")
RULE = RULES["synthseg_display"]
ORDER = ["Hippocampus", "Ventricles", "WholeBrain", "Entorhinal", "Fusiform", "MidTemp"]
NAMES = ["CN", "EMCI", "LMCI", "AD"]


def md_table(path: str) -> str:
    return "\n".join(l for l in (ROOT / path).read_text().splitlines() if l.startswith("|"))


def metrics_table() -> str:
    rows = [("KAN fusion (final, K2)", "Fusion model (final)"), ("Clinical specialist", "Clinical specialist"),
            ("MRI specialist (MRI-only mode), scan subjects", "MRI specialist (MRI-only mode)")]
    out = ["| System | Accuracy | Balanced accuracy | Macro-F1 | AD vs rest AUC |", "|---|---|---|---|---|"]
    for key, label in rows:
        s = T["systems"][key]
        out.append(f"| {label} | {s['acc']:.3f} | {s['bal_acc']:.3f} | {s['macro_f1']:.3f} | {s['ad_auc']:.3f} |")
    return "\n".join(out)


def agreement_table() -> str:
    out = ["| Ratio (volume / ICV) | ICC(2,1) [95% CI] | Bias vs FreeSurfer 5.1 | Percentile shown |", "|---|---|---|---|"]
    ok = {s for s in ORDER if AGR["ratios"][f"{s} / ICV"]["icc21"] >= RULE["min_icc21"]
          and abs(AGR["ratios"][f"{s} / ICV"]["bias_pct_of_fs_mean"]) <= RULE["max_abs_bias_pct"]}
    for s in ORDER:
        r = AGR["ratios"][f"{s} / ICV"]
        out.append(f"| {s} | {r['icc21']:.2f} [{r['icc21_ci95'][0]:.2f}, {r['icc21_ci95'][1]:.2f}] | "
                   f"{r['bias_pct_of_fs_mean']:+.0f}% | {'yes' if s in ok else 'no (low agreement)'} |")
    return "\n".join(out)


def weak(key):
    return "; ".join(EV[key]["weak_or_failed"])


def main():
    sev = T["severity"]["KAN fusion (final, K2)"]
    pop = REF["population"]
    parity = (ROOT / "tests/parity/RESULT.md").read_text()
    overall = re.search(r"Overall: \*\*(\w+)\*\*", parity).group(1)
    drift = md_table("tests/parity/DRIFT.md")
    cam = md_table("tests/parity/CAM_DENSITY.md")
    md = f"""# Model card: cognitive-stage assessment (fusion-v3)

**Research use only. Not a diagnostic device.** This page is generated by `tools/build_model_card.py` from committed
result files; it is the single source for the Model Card page of the app.

## What it is
A research prototype that stages cognitive status (CN, EMCI, LMCI, AD) from clinical assessments and a T1 MRI, using a
frozen system (freeze commit `{REG['freeze_commit']}`): five-seed clinical CatBoost specialists, a logistic-regression
MRI specialist (six volume ratios, a CNN AD score "ALZ", brain-age gap, age, sex), a DeepBrainNet brain-age model, a
3D ResNet CNN (15 checkpoints) and a KAN fusion layer that gives the final stage probabilities and an AD probability.
Severity is the expected stage index, a number from {RULES['severity_range'][0]} to {RULES['severity_range'][1]}, computed from the stage probabilities.
{len(REG['artifacts'])} artifacts are hash-checked against `src/assessment/artifacts/registry.json` before every run.

## Modes
| Mode | What it is |
|---|---|
| FULL | {MODE_LABELS['FULL']} |
| CLINICAL_ONLY | {MODE_LABELS['CLINICAL_ONLY']}: the frozen KAN run with the missing-scan inputs it was trained with; no MRI panels, no brain age, severity hidden |
| MRI_ONLY | {MODE_LABELS['MRI_ONLY']}: no 4-stage prediction and no severity |

If a scan fails quality control, a FULL request is downgraded to CLINICAL_ONLY and the report says so.

## Probabilities
Stage and AD probabilities are the frozen models' raw softmax outputs, shown as **model probability**. They have not
been adjusted after training, and their reliability as frequencies has not been measured.

## Frozen internal results (single run on the held-out ADNI test split, n = {T['n']})
{metrics_table()}

Severity means by stage for the fusion model rise monotonically ({', '.join(f'{m:.2f}' for m in sev['means'])}).
These numbers come from one frozen run on an internal ADNI split, `frozen_run/test_results.json`. They are not an external
validation, and the differences between the fusion model and the clinical specialist are within the bootstrap intervals in
that file. The 4-class metrics of the "MRI specialist (MRI-only mode)" row do not apply to MRI-only reports, which carry no stage;
see the dated correction under External validation.

## Reference population
Per-stage ranges (p25, p50, p75) and the pooled CN volume percentiles in the report come from the **{pop['n']} clinical-train subjects**
only (CN {pop['n_by_stage']['CN']}, EMCI {pop['n_by_stage']['EMCI']}, LMCI {pop['n_by_stage']['LMCI']}, AD {pop['n_by_stage']['AD']}).
Volume percentiles are **not age/sex-adjusted**. The frozen models were fitted on the train and validation subjects together, so the
reference tables describe a subset of the data the models saw.

## Reproducibility of the engine (parity)
The inference engine reproduces the stored outputs of the single frozen test run from the same stored inputs: **{overall}**
(all test scans scored in the frozen batch order, plus the one validation subject without a scan; tolerances declared before the run,
no labels read, no metrics computed).

{md_table('tests/parity/RESULT.md')}

**{ALZ_BATCH_CAVEAT}** The app scores one scan at a time; measured drift, not gated:

{drift}

Known difference: the LayerCAM region densities of a single-scan run differ slightly from the old card's.

{cam}

## SynthSeg volumes for new scans
The MRI specialist was trained on FreeSurfer 5.1 volumes. For uploaded scans the engine uses SynthSeg volumes instead. Agreement was
checked descriptively on {AGR['meta']['n_ok']} train scans (the raw native scans still on disk number far fewer than the full cohort, so the
intervals are wide). This is not a validation.

{agreement_table()}

Display rule: a percentile is shown only for ratios with ICC(2,1) of at least {RULE['min_icc21']:.2f} and absolute bias of at most {RULE['max_abs_bias_pct']}%. The other ratios
are shown raw, labelled "low agreement with training volumes, no percentile". The "MRI changed the stage" flag is not shown on SynthSeg
reports, and every such report carries a warning quoting these numbers. ADNI demo cases use the exact FreeSurfer volumes and the stored
m1 outputs, so they are not affected.

## Explanations and their status
Explanations are post-hoc and carry the pre-registered validation status:
- CNN attribution map: {weak('cnn')}. It is shown in the technical view only, as "attribution density, not evidence of disease location",
  with both sanity failures labelled. It is not shown in the clinician view.
- Clinical SHAP: {weak('clinical_shap')}.
- MRI-specialist SHAP: {weak('mri_shap')}.
- Fusion-layer Shapley values: {weak('kan')}.
Clinical explanations never refer to MRI features.

## Limitations
- ADNI only. Scanners, protocols and populations outside ADNI are a domain shift. Uploaded scans carry a domain-shift caveat.
- The staging task is hardest for LMCI (see the per-stage results in `frozen_run/test_results.md`); the MRI specialist detects AD better than it stages MCI.
- m1 preprocessing is not bit-reproducible: repeated runs on the same scan differ slightly.
- The system is cross-sectional. Reports for several visits of one person are independent assessments, not a forecast.
- Missing clinical inputs are replaced by training medians and listed in the report; required inputs (CDRSB, MMSE, ADAS13) cannot be missing.
- Demo cases come from the ADNI train or validation split and were in the training data of the frozen system, so their outputs are in-sample.
  The upload demonstration uses an ADNI scan to show the upload path; it is a demonstration, not a validation.
- The trained weights and any subject-level data are not part of any public release.

{oasis_render.card_section()}"""
    (ROOT / "docs" / "model_card.md").write_text(md)
    print("wrote docs/model_card.md")


if __name__ == "__main__":
    main()
